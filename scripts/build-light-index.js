#!/usr/bin/env node
/*
 * Generates js/data/index-light.js (window.DATA_INDEX): a compact index of the heavy datasets, so the
 * dashboard (#/), roadmap and account render without downloading ~6 MB of questions/lessons/algos.
 * App.lite(kind) / App.stats() / App.dueItems() read it until the full group is loaded (docs/PERFORMANCE.md).
 *
 *   node scripts/build-light-index.js           write the file (run after adding/changing content)
 *   node scripts/build-light-index.js --check   exit 1 if the checked-in file is stale (validate.js does this too)
 *
 * Only fields the light screens read are kept. Order = manifest load order (same as the full arrays).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'js', 'data');
const OUT_NAME = 'index-light.js';
const OUT = path.join(DATA, OUT_NAME);
const CMD = 'node scripts/build-light-index.js';
// groups the index summarises (everything else is either eager or not needed by light routes)
const SOURCE_GROUPS = ['questions', 'algos', 'lessons', 'sd', 'drills', 'companies'];

const pick = (o, keys) => {
  const r = {};
  keys.forEach(k => { if (o[k] !== undefined && o[k] !== null && o[k] !== '') r[k] = o[k]; });
  return r;
};

/** Build the file text from loaded globals ({QUESTIONS, ALGOS, LESSONS, SD_PROBLEMS, DRILLS, COMPANIES}). */
function build(w) {
  const arr = x => (Array.isArray(x) ? x : []).filter(i => i && i.id);
  const idx = {
    // [id, topic, level] (+ ['en', q] for English questions: the dashboard's speaking fallback shows q)
    questions: arr(w.QUESTIONS).map(q => q.lang === 'en' ? [q.id, q.topic, q.level, 'en', q.q] : [q.id, q.topic, q.level]),
    algos: arr(w.ALGOS).map(a => pick(a, ['id', 'title', 'difficulty', 'pattern'])),
    lessons: arr(w.LESSONS).map(l => pick(l, ['id', 'track', 'order', 'title', 'level', 'minutes'])),
    sd: arr(w.SD_PROBLEMS).map(p => pick(p, ['id', 'title'])),
    drills: arr(w.DRILLS).map(d => pick(d, ['id', 'kind', 'q', 'term', 'example', 'en'])),
    companies: arr(w.COMPANIES).map(c => pick(c, ['id', 'name', 'focus'])),
  };
  const lines = ['/*',
    ' * GENERATED by ' + CMD + ' — do not edit by hand. Compact index of the heavy data groups',
    ' * (questions, algos, lessons, sd, drills, companies) for light routes (#/, #/roadmap, #/account).',
    ' * Regenerate after adding content; node scripts/validate.js fails when this file is stale.',
    ' */',
    'window.DATA_INDEX = {'];
  Object.keys(idx).forEach((k, i, ks) => {
    lines.push('  ' + k + ': [');
    idx[k].forEach(x => lines.push('    ' + JSON.stringify(x) + ','));
    lines.push('  ]' + (i < ks.length - 1 ? ',' : ''));
  });
  lines.push('};', '');
  return lines.join('\n');
}

/** Load the source groups' files in manifest order into a fresh sandbox and return its window. */
function loadSources() {
  const M = require(path.join(ROOT, 'js', 'core', 'data-manifest.js'));
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  for (const g of SOURCE_GROUPS) for (const f of M.groups[g] || []) {
    vm.runInContext(fs.readFileSync(path.join(DATA, f), 'utf8'), sandbox, { filename: f });
  }
  return sandbox.window;
}

const current = () => { try { return fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n'); } catch (e) { return null; } };

module.exports = { build, loadSources, current, OUT_NAME, CMD, SOURCE_GROUPS };

if (require.main === module) {
  const text = build(loadSources());
  if (process.argv.includes('--check')) {
    if (current() !== text) { console.error(OUT_NAME + ' đã cũ (stale). Chạy: ' + CMD); process.exit(1); }
    console.log(OUT_NAME + ' OK (' + Buffer.byteLength(text) + ' bytes).');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('Đã ghi js/data/' + OUT_NAME + ' (' + (Buffer.byteLength(text) / 1024).toFixed(1) + ' KB).');
  }
}
